const LANG_KEY = "forma_lang";
// Arabic removed: always English
function currentLang() { return "en"; }
function setLang(lang) { localStorage.setItem(LANG_KEY, "en"); applyLang("en"); }
function toggleLang() { /* disabled */ }
function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyLang(lang);
}
function t(key) {
  const lang = currentLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || key;
}
function applyLang(lang) {
  lang = lang || currentLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === "ar") ? "rtl" : "ltr";
  // translate data-i18n elements
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.hasAttribute("placeholder") && !el.hasAttribute("data-i18n-placeholder")) {
        el.placeholder = val;
      }
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  // update toggle button label
  document.querySelectorAll("[data-lang-toggle]").forEach(btn => {
    btn.textContent = lang === "ar" ? "EN" : "AR";
  });
  // re-render dynamic parts if needed
  if (typeof window.onLangChange === "function") window.onLangChange(lang);
}
function toggleLang() {
  setLang(currentLang() === "ar" ? "en" : "ar");
}

// apply on load
document.addEventListener("DOMContentLoaded", () => applyLang(currentLang()));